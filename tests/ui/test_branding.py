@pytest.mark.parametrize("name", PAGES)
def test_every_page_has_one_png_favicon_and_loads_the_brand_styles(name: str) -> None:
    html = (SITE / name).read_text(encoding="utf-8")
    links = re.findall(r'<link rel="icon"[^>]*>', html)
    assert len(links) == 1, links
    match = re.search(r'type="image/png"[^>]*href="data:image/png;base64,([^"]+)"', links[0])
    assert match, links[0][:120]
    png = base64.b64decode(match.group(1))
    assert png[:8] == b"\x89PNG\r\n\x1a\n"
    width, height = struct.unpack(">II", png[16:24])
    assert (width, height) == (64, 64) and len(png) < 12_000
    assert 'href="brand.css"' in html and "brand-dot" not in html
    assert html.count('class="brand-logo"') == 1


def test_the_brand_styles_carry_two_webp_images_and_nothing_remote() -> None:
    css = (SITE / "brand.css").read_text(encoding="utf-8")
    assert css.startswith("/* GENERATED by tools/make_brand_assets.py")
    images = re.findall(r'url\("data:image/webp;base64,([^"]+)"\)', css)
    assert len(images) == 2, "the mark and the watermark"
    sizes = []
    for data in images:
        raw = base64.b64decode(data)
        assert raw[:4] == b"RIFF" and raw[8:12] == b"WEBP"
        sizes.append(len(raw))
    assert sizes[0] < 12_000 and sizes[1] < 60_000, sizes  # a small mark, a modest watermark
    assert not re.findall(r"url\((?!\"data:)", css), "every image is a data: URI"
    assert "http" not in css.replace("http://www.w3.org", ""), "nothing is fetched"


def test_the_site_policy_allows_data_images_and_nothing_remote() -> None:
    policy = (SITE / "vercel.json").read_text(encoding="utf-8")
    img_src = re.search(r"img-src ([^;\"]+)", policy).group(1)  # type: ignore[union-attr]
    assert "data:" in img_src and "http" not in img_src and "*" not in img_src, img_src


def test_the_master_and_the_tool_that_makes_the_assets_are_in_the_repo() -> None:
    master = SITE.parent / "docs" / "brand" / "hashcam-logo.png"
    assert master.read_bytes()[:8] == b"\x89PNG\r\n\x1a\n"
    assert (SITE.parent / "tools" / "make_brand_assets.py").exists()


# ---------------------------------------------------------------- the mark beside the wordmark


@pytest.mark.parametrize("name", PAGES)
def test_the_top_bar_shows_the_mark_centred_on_the_wordmark(
    browser: Any, origin: str, how: str, name: str
) -> None:
    page, requests = open_page(browser, origin, name, how)
    assert page.locator(".brand-dot").count() == 0
    logo = page.locator(".brand .brand-logo")
    expect(logo).to_have_count(1)
    assert logo.get_attribute("aria-hidden") == "true"
    style = logo.evaluate(
        "n => { const s = getComputedStyle(n); return [s.width, s.height, s.backgroundImage.indexOf('data:image/webp;base64,') > 0, s.display]; }"
    )
    assert style == ["28px", "28px", True, "block"], style
    brand = page.locator(".brand").evaluate(
        "n => { const s = getComputedStyle(n); return [s.alignItems, s.columnGap]; }"
    )
    assert brand == ["center", "10px"], brand
    box, outer = logo.bounding_box(), page.locator(".brand").bounding_box()
    assert box is not None and outer is not None
    assert abs((box["y"] + box["height"] / 2) - (outer["y"] + outer["height"] / 2)) <= 1
    words = page.locator(".brand").evaluate(
        "n => { const r = document.createRange(); r.setStartAfter(n.firstElementChild); r.setEndAfter(n.lastChild); return r.getBoundingClientRect().left; }"
    )
    assert words >= box["x"] + box["width"] + 9, "10px between the mark and the words"
    assert [r for r in requests if r.startswith("image ")] == [], requests  # nothing is fetched
    page.close()


@pytest.mark.parametrize("name", PAGES)
def test_the_mark_turns_a_little_on_hover_and_returns(browser: Any, origin: str, name: str) -> None:
    page, _ = open_page(browser, origin, name, "http")
    logo = page.locator(".brand .brand-logo")
    assert logo.evaluate("n => getComputedStyle(n).transform") == "none"
    transition = logo.evaluate(
        "n => { const s = getComputedStyle(n); return [s.transitionProperty, s.transitionTimingFunction, s.transitionDuration]; }"
    )
    assert transition == ["transform", EASE, "0.5s"], (
        transition
    )  # compositor-only, the site's easing
    page.locator(".brand").hover()
    expect(logo).not_to_have_css("transform", "none")
    page.mouse.move(700, 500)
    expect(logo).to_have_css("transform", "none")
    page.close()


def test_the_mark_does_not_animate_under_reduced_motion(browser: Any, origin: str) -> None:
    page, _ = open_page(browser, origin, "index.html", "http", reduced_motion="reduce")
    duration = page.locator(".brand .brand-logo").evaluate(
        "n => getComputedStyle(n).transitionDuration"
    )
    assert duration in ("0s", "0.0001s", "1e-05s"), duration
    page.close()


# ---------------------------------------------------------------- the watermark


@pytest.mark.parametrize("name", PAGES)
def test_the_watermark_sits_behind_the_page_and_gets_in_no_one_s_way(
    browser: Any, origin: str, name: str
) -> None:
    page, _ = open_page(browser, origin, name, "http", viewport={"width": 1280, "height": 800})
    mark = page.evaluate(
        "(() => { const s = getComputedStyle(document.body, '::before'); return [s.position, s.zIndex, s.pointerEvents, Number(s.opacity), s.backgroundImage.slice(0, 30)]; })()"
    )
    assert (
        mark[:3] == ["fixed", "-1", "none"]
        and 0 < mark[3] <= 0.15
        and mark[4].startswith('url("data:image/webp')
    ), mark
    # Nothing is covered: the button under the watermark is the thing a click lands on.
    target = {
        "index.html": "#launchSandbox",
        "range.html": "#scoreBtn",
        "about.html": "#aboutCta",
        "audit.html": "#auditMail",
        "pro.html": "#licenseCheck",
        "policy.html": "#polTry",
    }.get(name, "#exportBtn, .flight")
    hit = page.evaluate(
        "(sel) => { const n = document.querySelector(sel); n.scrollIntoView({ block: 'center', behavior: 'instant' }); const r = n.getBoundingClientRect(); const top = document.elementFromPoint(r.x + r.width / 2, r.y + r.height / 2); return n.contains(top); }",
        target,
    )
    assert hit is True
    for width in (1280, 375):
        page.set_viewport_size({"width": width, "height": 800})
        assert page.evaluate("document.documentElement.scrollWidth <= innerWidth"), width
    page.emulate_media(media="print")
    assert page.evaluate("getComputedStyle(document.body, '::before').display") == "none"
    page.close()


@pytest.mark.parametrize("name", PAGES)
def test_the_branding_needs_no_network(browser: Any, origin: str, how: str, name: str) -> None:
    page, requests = open_page(browser, origin, name, how)
    page.wait_for_timeout(500)
    base = origin if how == "http" else "file:"
    remote = [r for r in requests if not r.split(" ", 1)[1].startswith((base, "data:", "blob:"))]
    assert remote == [], remote
    assert [r for r in requests if r.startswith("image ")] == [], "no image file is requested"
    page.close()
