"""The HashCam "H" logo: favicon, the mark beside the wordmark, and the page watermark.

* Every page in site/ has one PNG favicon as a data: URI, and loads `brand.css`, whose two images
  (the mark and the watermark) are data: URIs too, so there is no image request and it works offline.
* The top bar shows the mark in place of the old dot, centred on the wordmark; it turns a little on
  hover (a transform with the site's one easing) and stays still under reduced motion.
* The watermark sits behind the page, ignores the pointer, adds no scrolling and hides under print.

Needs only a browser.
"""

# ruff: noqa: E501  (page-side JavaScript in strings)

from __future__ import annotations

import base64
import re
import struct
from collections.abc import Iterator
from typing import Any

import pytest

from tests.ui.sitehelp import SITE, serve_site

sync_api = pytest.importorskip("playwright.sync_api")
expect = sync_api.expect

PAGES = sorted(p.name for p in SITE.glob("*.html"))
EASE = "cubic-bezier(0.16, 1, 0.3, 1)"


@pytest.fixture(scope="module")
def origin() -> Iterator[str]:
    with serve_site() as base:
        yield base


@pytest.fixture(scope="module")
def browser() -> Iterator[Any]:
    with sync_api.sync_playwright() as p:
        b = p.chromium.launch()
        yield b
        b.close()


@pytest.fixture(params=["http", "file"])
def how(request: pytest.FixtureRequest) -> str:
    return str(request.param)


def open_page(browser: Any, origin: str, name: str, how: str, **kw: Any) -> tuple[Any, list[str]]:
    page = browser.new_page(**kw)
    page.set_default_timeout(20_000)
    requests: list[str] = []
    page.on("request", lambda r: requests.append(f"{r.resource_type} {r.url}"))
    page.goto(f"{origin}/{name}" if how == "http" else (SITE / name).as_uri())
    return page, requests


