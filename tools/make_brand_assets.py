"""Make the site's logo assets from the HashCam "H" master image.

    python tools/make_brand_assets.py [docs/brand/hashcam-logo.png]

Needs Pillow (`pip install pillow`); it is a one-off design tool, not a build step. Writes:

* `site/brand.css`: the logo beside the wordmark (a small WebP with a transparent background) and a
  faint, large copy as a page watermark. Both are `data:` URIs inside the CSS, so the pages make no
  image request and work offline.
* the favicon in `<head>` of every page in `site/` (64px PNG on a dark rounded tile, a data: URI).
* `site/range/report-art.js` and `extension/report-art.js`: the logo and a faint watermark as JPEG,
  for the PDF report; `extension/brand.css`: the page watermark for the extension's side panel.

The master is a flat dark-navy picture. The background is found by flood-filling from the edges, so
dark parts inside the letter stay opaque.
"""

from __future__ import annotations

import base64
import io
import re
import sys
from collections import deque
from pathlib import Path

try:
    from PIL import Image, ImageDraw, ImageFilter, ImageOps
except ImportError:  # pragma: no cover - a hint, not logic
    raise SystemExit("this tool needs Pillow: pip install pillow") from None

REPO = Path(__file__).resolve().parents[1]
SITE = REPO / "site"
TILE = (8, 11, 18)  # the site's background, #080B12
BACKGROUND_TOLERANCE = 20  # how far from the master's navy still counts as background
SLATE = (148, 163, 184)  # --hc-muted, the page's secondary text colour
TRIM = 3  # the master has a faint frame on its outer pixels


def cut_out(master: Image.Image) -> Image.Image:
    """The glyph on a transparent background."""
    rgb = master.convert("RGB").crop((TRIM, TRIM, master.width - TRIM, master.height - TRIM))
    w, h = rgb.size
    px = rgb.load()
    corners = [px[2, 2], px[w - 3, 2], px[2, h - 3], px[w - 3, h - 3]]
    bg = tuple(sum(c[i] for c in corners) // 4 for i in range(3))

    def is_background(x: int, y: int) -> bool:
        p = px[x, y]
        return max(abs(p[0] - bg[0]), abs(p[1] - bg[1]), abs(p[2] - bg[2])) <= BACKGROUND_TOLERANCE

    outside = bytearray(w * h)
    queue: deque[tuple[int, int]] = deque()
    for x in range(w):
        queue.extend([(x, 0), (x, h - 1)])
    for y in range(h):
        queue.extend([(0, y), (w - 1, y)])
    while queue:
        x, y = queue.popleft()
        if not (0 <= x < w and 0 <= y < h) or outside[y * w + x] or not is_background(x, y):
            continue
        outside[y * w + x] = 1
        queue.extend([(x + 1, y), (x - 1, y), (x, y + 1), (x, y - 1)])
    alpha = Image.new("L", (w, h), 255)
    alpha.putdata([0 if outside[i] else 255 for i in range(w * h)])
    alpha = alpha.filter(ImageFilter.GaussianBlur(0.9))  # soft, antialiased edge
    out = rgb.convert("RGBA")
    out.putalpha(alpha)
    box = alpha.point(lambda v: 255 if v > 24 else 0).getbbox()
    if box is None:
        raise SystemExit("no glyph found in the master image")
    return out.crop(box)


def square(glyph: Image.Image, size: int, pad: float = 0.04) -> Image.Image:
    side = max(glyph.size)
    canvas = Image.new("RGBA", (round(side * (1 + 2 * pad)),) * 2, (0, 0, 0, 0))
    canvas.paste(glyph, ((canvas.width - glyph.width) // 2, (canvas.height - glyph.height) // 2))
    return canvas.resize((size, size), Image.LANCZOS)


def tinted(glyph: Image.Image) -> Image.Image:
    """One tone (the page's slate) in the glyph's own shape, with its light kept as gentle shading:
    the letter stays readable, the amber orb loses its colour, and it sits quietly on the page."""
    light = ImageOps.autocontrast(glyph.convert("L"), cutoff=2)
    shade = light.point(lambda v: round(115 + 140 * v / 255))  # 0.45 .. 1.0 of the glyph's opacity
    shaded = Image.new("L", glyph.size)
    shaded.putdata(
        [
            a * s // 255
            for a, s in zip(glyph.getchannel("A").getdata(), shade.getdata(), strict=True)
        ]
    )
    out = Image.new("RGBA", glyph.size, (*SLATE, 0))
    out.putalpha(shaded)
    return out


def encode(image: Image.Image, fmt: str, **options: object) -> tuple[bytes, str]:
    buffer = io.BytesIO()
    image.save(buffer, fmt, **options)
    return buffer.getvalue(), f"image/{fmt.lower()}"


def data_uri(raw: bytes, mime: str) -> str:
    return f"data:{mime};base64," + base64.b64encode(raw).decode("ascii")


def favicon(glyph: Image.Image) -> bytes:
    size = 64
    tile = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    ImageDraw.Draw(tile).rounded_rectangle((0, 0, size - 1, size - 1), radius=14, fill=(*TILE, 255))
    mark = square(glyph, 50, pad=0.0)
    tile.alpha_composite(mark, ((size - 50) // 2, (size - 50) // 2))
    return encode(tile, "PNG", optimize=True)[0]


BRAND_CSS = """\
/* GENERATED by tools/make_brand_assets.py from docs/brand/hashcam-logo.png: do not edit.
   The logo beside the wordmark, and a faint one-tone copy of it as the page watermark. Both are
   data: URIs, so the pages make no image request and work offline. */
.brand {{ display: inline-flex; align-items: center; gap: 10px; }}
.brand-logo {{ display: block; flex: none; width: 28px; height: 28px;
  background: url("{mark}") center / contain no-repeat;
  transition: transform .5s var(--ease, cubic-bezier(0.16, 1, 0.3, 1)); }}
.brand:hover .brand-logo,
.brand:focus-visible .brand-logo {{ transform: scale(1.1) rotate(-4deg); }}

/* The watermark: one tone, feathered into the page, behind everything, fixed to the window, deaf to
   the pointer. Its edges dissolve (a radial mask) so it reads as part of the background. */
body::before {{ content: ""; position: fixed; z-index: -1; right: -10vmin; bottom: -14vmin;
  width: min(92vmin, 860px); aspect-ratio: 1; pointer-events: none; opacity: .11;
  background: url("{watermark}") center / contain no-repeat;
  -webkit-mask-image: radial-gradient(closest-side, #000 64%, transparent 100%);
  mask-image: radial-gradient(closest-side, #000 64%, transparent 100%); }}
@media print {{ body::before {{ display: none; }} }}
"""

FAVICON = '<link rel="icon" type="image/png" sizes="64x64" href="{href}">'


def patch_page(path: Path, href: str) -> None:
    html = path.read_text(encoding="utf-8")
    html = re.sub(r'<link rel="icon"[^>]*>\n?', "", html)
    html = html.replace(
        '<span class="brand-dot" aria-hidden="true"></span>',
        '<span class="brand-logo" aria-hidden="true"></span>',
    )
    html = html.replace(
        '<link rel="stylesheet" href="theme.css">',
        FAVICON.format(href=href) + '\n<link rel="stylesheet" href="theme.css">',
        1,
    )
    if 'href="brand.css"' not in html:
        html = html.replace(
            '<link rel="stylesheet" href="motion.css">',
            '<link rel="stylesheet" href="motion.css">\n<link rel="stylesheet" href="brand.css">',
            1,
        )
    path.write_text(html, encoding="utf-8")


REPORT_ART_JS = """// GENERATED by tools/make_brand_assets.py from the H logo: do not edit.
// The art for the Range's PDF report, as JPEG (the one picture format a PDF holds as it is):
// the logo on the header's dark tile, and a faint copy on white as the page watermark.
window.HCReportArt = {{
  logo: {{ w: {lw}, h: {lh}, b64: "{logo}" }},
  mark: {{ w: {mw}, h: {mh}, b64: "{mark}" }},
}};
"""


REPORT_ART_MODULE = """// GENERATED by tools/make_brand_assets.py from the H logo: do not edit.
// The art for the PDF report (JPEG, the one picture format a PDF holds as it is): the logo on the
// header's dark tile, and a faint copy on white as the page watermark.
export const reportArt = {{
  logo: {{ w: {lw}, h: {lh}, b64: "{logo}" }},
  mark: {{ w: {mw}, h: {mh}, b64: "{mark}" }},
}};
"""

EXTENSION_CSS = """\
/* GENERATED by tools/make_brand_assets.py from the H logo: do not edit.
   A faint one-tone copy of the logo behind the side panel, as a data: URI (no image request). */
body::before {{ content: ""; position: fixed; z-index: -1; right: -22vmin; bottom: -10vmin;
  width: 130vmin; aspect-ratio: 1; pointer-events: none; opacity: .13;
  background: url("{watermark}") center / contain no-repeat;
  -webkit-mask-image: radial-gradient(closest-side, #000 64%, transparent 100%);
  mask-image: radial-gradient(closest-side, #000 64%, transparent 100%); }}
@media print {{ body::before {{ display: none; }} }}
"""


def report_art(glyph: Image.Image) -> tuple[int, int]:
    """site/range/report-art.js: the two pictures the PDF report draws."""
    logo = Image.new("RGBA", (144, 144), (*TILE, 255))
    logo.alpha_composite(square(glyph, 144, pad=0.0))
    faint = square(tinted(glyph), 480)
    faint.putalpha(faint.getchannel("A").point(lambda v: v * 15 // 100))  # barely there on paper
    mark = Image.new("RGBA", faint.size, (255, 255, 255, 255))
    mark.alpha_composite(faint)
    logo_raw = encode(logo.convert("RGB"), "JPEG", quality=90, optimize=True)[0]
    mark_raw = encode(mark.convert("RGB"), "JPEG", quality=72, optimize=True)[0]
    (SITE / "range" / "report-art.js").write_text(
        REPORT_ART_JS.format(
            lw=logo.width,
            lh=logo.height,
            logo=base64.b64encode(logo_raw).decode("ascii"),
            mw=mark.width,
            mh=mark.height,
            mark=base64.b64encode(mark_raw).decode("ascii"),
        ),
        encoding="utf-8",
    )
    parts = {
        "lw": logo.width,
        "lh": logo.height,
        "logo": base64.b64encode(logo_raw).decode("ascii"),
        "mw": mark.width,
        "mh": mark.height,
        "mark": base64.b64encode(mark_raw).decode("ascii"),
    }
    (REPO / "extension" / "report-art.js").write_text(
        REPORT_ART_MODULE.format(**parts), encoding="utf-8"
    )
    watermark = encode(square(tinted(glyph), 512), "WEBP", quality=60, alpha_quality=45, method=6)
    (REPO / "extension" / "brand.css").write_text(
        EXTENSION_CSS.format(watermark=data_uri(*watermark)), encoding="utf-8"
    )
    return len(logo_raw), len(mark_raw)


def main() -> int:
    source = (
        Path(sys.argv[1]) if len(sys.argv) > 1 else REPO / "docs" / "brand" / "hashcam-logo.png"
    )
    glyph = cut_out(Image.open(source))
    mark, mark_mime = encode(square(glyph, 96), "WEBP", quality=92, method=6)
    watermark, wm_mime = encode(
        square(tinted(glyph), 512), "WEBP", quality=60, alpha_quality=45, method=6
    )
    icon = favicon(glyph)
    (SITE / "brand.css").write_text(
        BRAND_CSS.format(mark=data_uri(mark, mark_mime), watermark=data_uri(watermark, wm_mime)),
        encoding="utf-8",
    )
    for page in sorted(SITE.glob("*.html")):
        patch_page(page, data_uri(icon, "image/png"))
    print(f"mark {len(mark)} B, watermark {len(watermark)} B, favicon {len(icon)} B")
    logo_size, mark_size = report_art(glyph)
    print(f"report art: logo {logo_size} B, watermark {mark_size} B (site/range/report-art.js)")
    pages = [p.name for p in sorted(SITE.glob("*.html"))]
    print(f"site/brand.css {(SITE / 'brand.css').stat().st_size} B; pages patched: {pages}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
