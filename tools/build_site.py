"""Build the public HashCam site in site/ (a static folder, deployed as is).

    python tools/build_site.py [--samples --dsn postgresql://...]

1. Copies the shared files from ui/ (theme, styles, GSAP, the font), so ui/ stays the one source.
   The nine animation styles (`ui/fx3d.js`, an ES module the extension imports) are turned into a
   classic script `site/fx3d.js` that sets `window.HCFX`: a module script cannot load from a
   `file://` page, and the site must work when opened straight from disk.
2. Builds the receipt verifier for the browser (`core/abb-wasm`, target wasm32-unknown-unknown,
   size-optimized) and copies it to site/verifier.wasm. Needs
   `rustup target add wasm32-unknown-unknown`.
3. Writes site/offline-data.js: the verifier and the sample receipts as base64. Only loaded on a
   `file://` page, where `fetch()` of a neighbouring file is not allowed.
4. With --samples: makes the sample receipts with the real recorder (signer, ledger, abb):
   one genuine receipt, the same with one event edited, and its key manifest. They hold only
   made-up addresses and demo keys made for that one run.
"""

from __future__ import annotations

import argparse
import base64
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
import zipfile
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
SITE = REPO / "site"
SHARED = ["theme.css", "console.css"]
VENDOR = ["gsap.min.js", "LICENSE-gsap.txt", "plus-jakarta-sans.woff2", "OFL-plus-jakarta-sans.txt"]
_EXPORT = re.compile(r"^export (function|const) (\w+)", re.MULTILINE)


def to_classic(module_source: str, name: str = "fx3d", global_name: str = "HCFX") -> str:
    """`ui/<name>.js` (an ES module) as a classic script: one function scope, `window.<global>`."""
    names = [exported for _, exported in _EXPORT.findall(module_source)]
    if not names or re.search(r"^import ", module_source, re.MULTILINE):
        raise SystemExit(f"ui/{name}.js must export names and import nothing")
    body = _EXPORT.sub(r"\1 \2", module_source)
    return (
        f"// GENERATED by tools/build_site.py from ui/{name}.js: do not edit. A classic script,\n"
        f"// so it also loads from a file:// page. Reached as window.{global_name}.\n"
        "(function () {\n"
        '"use strict";\n'
        f"{body}\n"
        f"window.{global_name} = {{ {', '.join(names)} }};\n"
        "})();\n"
    )


# ES modules in ui/ that the site needs as classic scripts: (file, global name).
CLASSIC = [("fx3d", "HCFX"), ("readable", "HCReadable")]
# Files the extension keeps its own byte-identical copy of (a test checks they match).
EXTENSION_COPIES = ["theme.css", "fx3d.js", "readable.js"]


def copy_shared() -> None:
    for name in SHARED:
        shutil.copyfile(REPO / "ui" / name, SITE / name)
    for name, global_name in CLASSIC:
        source = (REPO / "ui" / f"{name}.js").read_text(encoding="utf-8")
        (SITE / f"{name}.js").write_text(to_classic(source, name, global_name), encoding="utf-8")
    for name in EXTENSION_COPIES:
        shutil.copyfile(REPO / "ui" / name, REPO / "extension" / name)
    (SITE / "vendor").mkdir(exist_ok=True)
    for name in VENDOR:
        shutil.copyfile(REPO / "ui" / "vendor" / name, SITE / "vendor" / name)


def build_wasm() -> None:
    target_dir = os.environ.get("CARGO_TARGET_DIR", str(REPO / "core" / "target"))
    # Size, not speed, matters here: visitors download it.
    env = {
        **os.environ,
        "CARGO_PROFILE_RELEASE_OPT_LEVEL": "s",
        "CARGO_PROFILE_RELEASE_LTO": "true",
        "CARGO_PROFILE_RELEASE_CODEGEN_UNITS": "1",
        "CARGO_PROFILE_RELEASE_STRIP": "true",
        "CARGO_PROFILE_RELEASE_PANIC": "abort",
    }
    subprocess.run(  # noqa: S603 - fixed argv
        [  # noqa: S607 - cargo comes from the developer's PATH
            "cargo",
            "build",
            "--release",
            "--target",
            "wasm32-unknown-unknown",
            "--manifest-path",
            str(REPO / "core" / "Cargo.toml"),
            "-p",
            "abb-wasm",
        ],
        check=True,
        env=env,
    )
    built = Path(target_dir) / "wasm32-unknown-unknown" / "release" / "abb_wasm.wasm"
    shutil.copyfile(built, SITE / "verifier.wasm")
    print(f"verifier.wasm: {built.stat().st_size // 1024} KB")


def write_offline_data() -> None:
    """The verifier and the samples as base64, for a page opened from disk."""

    def b64(path: Path) -> str:
        return base64.b64encode(path.read_bytes()).decode("ascii")

    samples = SITE / "samples"
    data = {
        "wasm": b64(SITE / "verifier.wasm"),
        "genuine": b64(samples / "genuine.abbreceipt"),
        "edited": b64(samples / "edited.abbreceipt"),
        "keys": b64(samples / "sample.keys.json"),
    }
    (SITE / "offline-data.js").write_text(
        "// GENERATED by tools/build_site.py: the verifier and the sample receipts as base64.\n"
        "// Loaded only when the page is opened from a file:// address.\n"
        f"window.HC_OFFLINE = {json.dumps(data)};\n",
        encoding="utf-8",
    )


def make_samples(dsn: str) -> None:
    sys.path.insert(0, str(REPO))
    from services.recorder.session import Recorder

    work = Path(tempfile.mkdtemp(prefix="site-samples-"))
    recorder = Recorder.start(admin_dsn=dsn, work=work, receipts=work / "receipts")
    try:
        s = recorder.start_session(
            task="Order one notebook on shop.example",
            agent="Sample agent",
            passport={"hosts": ["shop.example"], "minutes": 30},
        )
        recorder.report(s, {"kind": "navigate", "url": "https://shop.example/"})
        recorder.report(s, {"kind": "navigate", "url": "https://bank.example/transfer"})  # blocked
        sealed = recorder.stop(s, killed=False)
        receipt = work / "receipts" / sealed["receipt"]
        out = SITE / "samples"
        out.mkdir(exist_ok=True)
        shutil.copyfile(receipt, out / "genuine.abbreceipt")
        shutil.copyfile(receipt.with_name(receipt.name + ".keys.json"), out / "sample.keys.json")
        edit_one_event(receipt, out / "edited.abbreceipt")
        print("samples:", sealed["verdict"]["overall"])
    finally:
        recorder.close()
        shutil.rmtree(work, ignore_errors=True)


def edit_one_event(src: Path, dst: Path) -> None:
    """Change one event's address, as someone editing the record afterwards would."""
    with zipfile.ZipFile(src) as archive:
        document = json.loads(archive.read("receipt.json"))
        others = {n: archive.read(n) for n in archive.namelist() if n != "receipt.json"}
    for item in document["events"]:
        event = json.loads(base64.b64decode(item["canonical_b64"]))
        if event["event_type"] == "ACTION_REQUESTED":
            event["payload"]["target"] = "https://shop.example/harmless"
            item["canonical_b64"] = base64.b64encode(
                json.dumps(event, sort_keys=True, separators=(",", ":")).encode()
            ).decode()
            break
    with zipfile.ZipFile(dst, "w") as archive:
        archive.writestr("receipt.json", json.dumps(document))
        for name, data in others.items():
            archive.writestr(name, data)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--samples", action="store_true")
    parser.add_argument("--no-wasm", action="store_true")
    parser.add_argument("--dsn", default=os.environ.get("ABB_TEST_DSN", ""))
    args = parser.parse_args()
    copy_shared()
    if args.samples:
        if not args.dsn:
            parser.error("--samples needs --dsn (or ABB_TEST_DSN)")
        make_samples(args.dsn)
    if not args.no_wasm:
        build_wasm()
    if (SITE / "verifier.wasm").exists() and (SITE / "samples" / "genuine.abbreceipt").exists():
        write_offline_data()
    print(f"site ready in {SITE}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
